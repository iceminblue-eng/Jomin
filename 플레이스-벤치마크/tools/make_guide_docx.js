const TABLE_BORDERS = { top: border(), bottom: border(), left: border(), right: border(), insideHorizontal: border(), insideVertical: border() };
const NO_BORDERS = { top: noBorder(), bottom: noBorder(), left: noBorder(), right: noBorder(), insideHorizontal: noBorder(), insideVertical: noBorder() };

function cell(content, w, opt = {}) {
  const children = Array.isArray(content) ? content : [new Paragraph({ children: runs(content, { size: opt.size || 18, bold: opt.bold, color: opt.color }), spacing: { after: 40, line: 300 }, alignment: opt.align })];
  return new TableCell({
    children, width: { size: w, type: WidthType.DXA },
    shading: opt.fill ? { type: ShadingType.CLEAR, fill: opt.fill, color: 'auto' } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    verticalAlign: opt.valign || VerticalAlign.TOP,
    columnSpan: opt.span,
  });
}
// table({cols:[비율...], head:[...], rows:[[...]], headFill, firstColBold})
function table({ cols, head, rows, headFill = PAPER, firstColBold = false, fills = [] }) {
  const sum = cols.reduce((a, b) => a + b, 0);
  const widths = cols.map(c => Math.round(CONTENT_W * c / sum));
  const trs = [];
  if (head) trs.push(new TableRow({ tableHeader: true, children: head.map((h, i) => cell(h, widths[i], { bold: true, fill: headFill, size: 17, color: INK2 })) }));
  rows.forEach((r, ri) => trs.push(new TableRow({ children: r.map((c, i) => cell(c, widths[i], { bold: firstColBold && i === 0, fill: (fills[ri] || [])[i] })) })));
  return new Table({ width: { size: CONTENT_W, type: WidthType.DXA }, columnWidths: widths, borders: TABLE_BORDERS, rows: trs });
}
function callout(text, fill = PINE_SOFT, bar = PINE) {
  const w1 = 90, w2 = CONTENT_W - 90;
  return new Table({
    width: { size: CONTENT_W, type: WidthType.DXA }, columnWidths: [w1, w2], borders: NO_BORDERS,
    rows: [new TableRow({ children: [
      new TableCell({ children: [new Paragraph('')], width: { size: w1, type: WidthType.DXA }, shading: { type: ShadingType.CLEAR, fill: bar, color: 'auto' } }),
      new TableCell({ children: (Array.isArray(text) ? text : [text]).map(t => new Paragraph({ children: runs(t, { size: 19 }), spacing: { after: 60, line: 320 } })), width: { size: w2, type: WidthType.DXA }, shading: { type: ShadingType.CLEAR, fill, color: 'auto' }, margins: { top: 120, bottom: 120, left: 180, right: 180 } }),
    ] })],
  });
}
// figs([{img:'bench_p05_1.jpg', cap:'...'}], {wide:false})
function figs(items, opt = {}) {
  const n = items.length;
  const w = Math.round(CONTENT_W / n);
  const pxTotal = 580 - 12 * n;
  const cells = items.map(it => {
    const file = path.join(IMG, it.img);
    const children = [];
    if (fs.existsSync(file)) {
      const dim = jpegSize(file);
      const maxW = Math.round(pxTotal / n), maxH = opt.maxH || 330;
      let width = maxW, height = Math.round(dim.h * width / dim.w);
      if (height > maxH) { height = maxH; width = Math.round(dim.w * height / dim.h); }
      children.push(new Paragraph({ alignment: AlignmentType.CENTER, children: [new ImageRun({ type: 'jpg', data: fs.readFileSync(file), transformation: { width, height } })], spacing: { after: 40 } }));
    } else children.push(new Paragraph({ children: [new TextRun({ text: `[이미지 없음: ${it.img}]`, color: 'AA0000' })] }));
    children.push(new Paragraph({ alignment: AlignmentType.CENTER, children: runs(it.cap || '', { size: 16, color: INK3 }), spacing: { after: 60, line: 260 } }));
    return new TableCell({ children, width: { size: w, type: WidthType.DXA }, margins: { top: 60, bottom: 60, left: 60, right: 60 }, verticalAlign: VerticalAlign.TOP });
  });
  return new Table({ width: { size: CONTENT_W, type: WidthType.DXA }, columnWidths: items.map(() => w), borders: NO_BORDERS, rows: [new TableRow({ children: cells })] });
}
function jpegSize(file) {
  const b = fs.readFileSync(file); let i = 2;
  while (i < b.length) { if (b[i] !== 0xFF) { i++; continue; } const m = b[i + 1]; if (m >= 0xC0 && m <= 0xCF && m !== 0xC4 && m !== 0xC8 && m !== 0xCC) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) }; i += 2 + b.readUInt16BE(i + 2); }
  return { w: 770, h: 1499 };
}
