function runs(text, base = {}) {
  // **굵게** 마크업만 지원
  const out = [];
  String(text).split(/(\*\*[^*]+\*\*)/g).forEach(seg => {
    if (!seg) return;
    if (seg.startsWith('**') && seg.endsWith('**')) out.push(new TextRun({ text: seg.slice(2, -2), bold: true, ...base }));
    else out.push(new TextRun({ text: seg, ...base }));
  });
  return out;
}
